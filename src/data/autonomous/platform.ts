function hist(
  id: string,
  at: string,
  result: 'success' | 'failed' | 'partial',
  summary: string,
  durationMinutes: number,
  confidence: number,
) {
  return { id, at, result, summary, durationMinutes, confidence }
}

function log(id: string, at: string, level: 'info' | 'warning' | 'error' | 'reasoning', message: string) {
  return { id, at, level, message }
}

function retry(id: string, at: string, attempt: number, reason: string, outcome: 'retried' | 'abandoned' | 'succeeded') {
  return { id, at, attempt, reason, outcome }
}

