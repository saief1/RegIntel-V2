import type { DocumentKind, DocumentSection, DocumentStatus, KnowledgeDocument } from '../types/knowledge'

/**
 * Static seed content for the regulation library. This is illustrative
 * placeholder content for an enterprise regulatory-intelligence UI — titles,
 * jurisdictions and summaries are representative of the domain, not
 * transcriptions of any real statute or filing.
 */

