export const DOCUMENTS: KnowledgeDocument[] = SEEDS.map((seed) => ({
  ...seed,
  relatedDocumentIds: seed.relatedDocumentIds ?? [],
  sections: buildSections(seed),
}))

const DOCUMENTS_BY_ID = new Map(DOCUMENTS.map((document) => [document.id, document]))

export function getDocumentById(id: string): KnowledgeDocument | undefined {
  return DOCUMENTS_BY_ID.get(id)
}

export const CATEGORIES: string[] = Array.from(new Set(DOCUMENTS.map((document) => document.category))).sort()

export const JURISDICTIONS: string[] = Array.from(new Set(DOCUMENTS.map((document) => document.jurisdiction))).sort()

export const STATUSES: DocumentStatus[] = ['active', 'proposed', 'draft', 'superseded']

export const ALL_TAGS: string[] = Array.from(new Set(DOCUMENTS.flatMap((document) => document.tags))).sort()
